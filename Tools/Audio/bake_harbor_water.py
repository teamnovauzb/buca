"""Original quiet stereo harbor-water loop; procedural synthesis, no external samples."""
import math
import random
import struct
import wave
from pathlib import Path

RATE = 24000
DURATION = 34
OVERLAP = 2
rng = random.Random(20261019)
channels = []
for channel in range(2):
    low = mid = high = 0.0
    samples = []
    events = []
    # Soft resonant droplets and small laps, rather than a constant broad hiss.
    for _ in range(170):
        start = rng.uniform(0, DURATION)
        events.append((int(start*RATE), rng.uniform(.025,.13), rng.uniform(450,1800), rng.uniform(.008,.025)))
    bubbles = [0.0] * (RATE*DURATION)
    for start, duration, frequency, gain in events:
        count = int(duration*RATE)
        for j in range(min(count, len(bubbles)-start)):
            age = j / RATE
            envelope = math.sin(math.pi*j/count)*math.exp(-age*16)
            phase = 2*math.pi*frequency*(age - 1.8*age*age)
            bubbles[start+j] += gain*envelope*math.sin(phase)
    for i in range(RATE*DURATION):
        t = i/RATE
        noise = rng.uniform(-1,1)
        low += .035*(noise-low)
        mid += .24*(noise-mid)
        high += .62*(noise-high)
        swell = (.52 + .20*math.sin(2*math.pi*t/7.3+channel*.6)
                 + .13*math.sin(2*math.pi*t/4.7+1.1+channel*.3))
        lap = max(0,math.sin(2*math.pi*t/2.9+channel*.65))**3
        value = low*(.22+.13*swell) + (mid-low)*(.11*swell+.07*lap) + (high-mid)*.008*lap
        samples.append(value + bubbles[i])
    # Crossfade the end into the start, then omit the consumed opening overlap.
    overlap=RATE*OVERLAP
    for i in range(overlap):
        weight=.5-.5*math.cos(math.pi*i/(overlap-1))
        samples[-overlap+i]=samples[-overlap+i]*(1-weight)+samples[i]*weight
    channels.append(samples[overlap:])
peak=max(abs(v) for ch in channels for v in ch)
gain=.56/max(peak,.001)
frames=bytearray()
for left,right in zip(*channels):
    frames.extend(struct.pack('<hh',round(left*gain*32767),round(right*gain*32767)))
path=Path('Assets/Audio/Ambience/EveningHarborWater.wav')
with wave.open(str(path),'wb') as stream:
    stream.setparams((2,2,RATE,0,'NONE','not compressed'))
    stream.writeframes(frames)
rms=math.sqrt(sum((v*gain)**2 for ch in channels for v in ch)/(2*len(channels[0])))
report=f'Original synthesized harbor water. Stereo, {RATE} Hz, {len(channels[0])/RATE:.0f} seconds, 16-bit PCM. Peak {20*math.log10(.56):.1f} dBFS, RMS {20*math.log10(rms):.1f} dBFS. Two-second loop crossfade; no external audio samples.\n'
Path('output/harbor-animation/audio-validation.txt').write_text(report)
Path('Assets/Audio/Ambience/SOURCE.txt').write_text('EveningHarborWater.wav is original procedural water ambience generated by Tools/Audio/bake_harbor_water.py for BUCA. No external recordings or third-party samples.\n')
print(report)
